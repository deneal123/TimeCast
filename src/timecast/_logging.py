"""Логирование библиотеки.

Библиотека НЕ конфигурирует логирование (это задача приложения), а лишь получает
именованный логгер. Веб-слой/приложение настраивают хендлеры и уровни.
"""
import logging


def setup_logging(name: str = "timecast") -> logging.Logger:
    """Возвращает именованный логгер библиотеки."""
    return logging.getLogger(name)
